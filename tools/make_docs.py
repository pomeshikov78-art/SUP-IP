def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs"))
    ap.add_argument("--version", default=None)
    a = ap.parse_args()
    ver = a.version
    if not ver:
        import re
        src = open(os.path.join(ROOT, "sup-ip", "server.py"), encoding="utf-8").read()
        ver = re.search(r'^VERSION = "([^"]+)"', src, re.M).group(1)
    today = datetime.date.today().strftime("%d.%m.%Y")
    total = []
    for name, doc in (("Руководство_пользователя", user_manual(ver, today)),
                      ("Руководство_администратора", admin_manual(ver, today))):
        for p, size in save(doc, a.out, name):
            print("%-70s %8.1f КиБ" % (p, size / 1024))
            total.append(p)
    print("Готово: %d файлов, версия %s" % (len(total), ver))
    return 0


