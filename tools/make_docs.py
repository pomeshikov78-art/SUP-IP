def word_html(d):
    """Word-совместимый .doc из тех же блоков документа."""
    html = docgen.html_bytes(d).decode("utf-8")
    html = html.replace(
        "<html lang=ru>",
        '<html xmlns:o="urn:schemas-microsoft-com:office:office" '
        'xmlns:w="urn:schemas-microsoft-com:office:word" '
        'xmlns="http://www.w3.org/TR/REC-html40" lang=ru>')
    html = html.replace(
        "<meta charset=utf-8>",
        '<meta charset=utf-8><meta http-equiv="Content-Type" content="text/html; charset=utf-8">'
        '<!--[if gte mso 9]><xml><w:WordDocument><w:View>Print</w:View><w:Zoom>100</w:Zoom>'
        '<w:DoNotOptimizeForBrowser/></w:WordDocument></xml><![endif]-->')
    html = html.replace(
        "@media print{body{margin:0}}",
        "@page WordSection1{size:595.3pt 841.9pt;margin:56.7pt 42.5pt 56.7pt 70.9pt}"
        "div.WordSection1{page:WordSection1}"
        "body{max-width:none;margin:0;font-size:11pt}"
        "h1{font-size:20pt}h2{font-size:14pt}h3{font-size:12pt}"
        "table{font-size:9.5pt}th,td{padding:3pt 4pt}"
        "@media print{body{margin:0}}")
    html = html.replace("<h1>", '<div class=WordSection1><h1>', 1)
    html = html.replace("</html>", "</div></html>")
    return html.encode("utf-8")


def save(d, outdir, name):
    os.makedirs(outdir, exist_ok=True)
    paths = []
    for ext, data in (("docx", docgen.render(d, "docx")), ("doc", word_html(d))):
        p = os.path.join(outdir, "%s.%s" % (name, ext))
        with open(p, "wb") as f:
            f.write(data)
        paths.append((p, len(data)))
    return paths


